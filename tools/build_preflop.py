"""Generate bot/sngbot/preflop_data.py: hand percentiles and range equities.

    python3 tools/build_preflop.py [--samples 1200] [--multi-samples 2500]

Steps: Monte Carlo the 169x169 class-vs-class all-in equity matrix (with exact
combo-compatibility counts for card removal), rank classes by equity versus a
random hand, then integrate each class's equity against the top-X% range for
every X in XGRID. Also estimates equity against 1..7 random opponents.
Takes ~30 s on 16 cores. Hold'em only: adapt deal sizes here if the
announced variant changes hole/board cards or the deck.
"""
import argparse
import os
import random
import sys
import time
from multiprocessing import Pool

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "bot"))
from sngbot.cards import class_cards, class_combos, class_name, evaluate  # noqa: E402

XGRID = (0.01, 0.02, 0.03, 0.05, 0.07, 0.10, 0.13, 0.16, 0.20, 0.25, 0.30,
         0.35, 0.40, 0.50, 0.60, 0.70, 0.85, 1.00)
OUT = os.path.join(ROOT, "bot", "sngbot", "preflop_data.py")
CARDS = [class_cards(k) for k in range(169)]


def _pair_job(args):
    pairs, samples, seed = args
    rng = random.Random(seed)
    out = []
    for i, j in pairs:
        compat = [(a, b) for a in CARDS[i] for b in CARDS[j] if not set(a) & set(b)]
        if i == j:
            out.append((i, j, 0.5, len(compat)))
            continue
        win = 0.0
        for _ in range(samples):
            a, b = compat[rng.randrange(len(compat))]
            used = {a[0], a[1], b[0], b[1]}
            board = rng.sample([c for c in range(52) if c not in used], 5)
            va = evaluate([a[0], a[1]] + board)
            vb = evaluate([b[0], b[1]] + board)
            win += 1.0 if va > vb else (0.5 if va == vb else 0.0)
        out.append((i, j, win / samples, len(compat)))
    return out


def _multi_job(args):
    k, samples, seed = args
    rng = random.Random(seed)
    row = []
    for n in range(1, 8):
        share = 0.0
        for _ in range(samples):
            h = CARDS[k][rng.randrange(len(CARDS[k]))]
            deck = [c for c in range(52) if c != h[0] and c != h[1]]
            deal = rng.sample(deck, 5 + 2 * n)
            board = deal[:5]
            mine = evaluate([h[0], h[1]] + board)
            best = mine
            ties = 1
            for o in range(n):
                v = evaluate(deal[5 + 2 * o:7 + 2 * o] + board)
                if v > best:
                    best, ties = v, 0
                    break
                if v == best:
                    ties += 1
            if best == mine and ties:
                share += 1.0 / ties
        row.append(round(1000 * share / samples))
    return k, tuple(row)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=1200)
    ap.add_argument("--multi-samples", type=int, default=2500)
    ap.add_argument("--procs", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    args = ap.parse_args()
    t0 = time.time()

    pairs = [(i, j) for i in range(169) for j in range(i, 169)]
    chunks = [pairs[c:c + 200] for c in range(0, len(pairs), 200)]
    M = [[0.5] * 169 for _ in range(169)]
    C = [[0] * 169 for _ in range(169)]
    with Pool(args.procs) as pool:
        jobs = [(ch, args.samples, 1000 + n) for n, ch in enumerate(chunks)]
        for res in pool.imap_unordered(_pair_job, jobs):
            for i, j, e, c in res:
                M[i][j], M[j][i] = e, 1.0 - e
                C[i][j] = C[j][i] = c
        print(f"pair matrix done in {time.time() - t0:.0f}s", flush=True)
        multi = dict(pool.imap_unordered(
            _multi_job, [(k, args.multi_samples, 5000 + k) for k in range(169)]))
    print(f"multiway done in {time.time() - t0:.0f}s", flush=True)

    eqr = [sum(C[i][j] * M[i][j] for j in range(169)) / sum(C[i]) for i in range(169)]
    order = sorted(range(169), key=lambda k: -eqr[k])
    start = [0.0] * 169
    width = [0.0] * 169
    pct = [0.0] * 169
    acc = 0
    for k in order:
        n = class_combos(k)
        start[k] = acc / 1326.0
        width[k] = n / 1326.0
        pct[k] = (acc + n / 2.0) / 1326.0
        acc += n

    eq = []
    for i in range(169):
        row = []
        for x in XGRID:
            num = den = 0.0
            for j in range(169):
                w = (x - start[j]) / width[j]
                if w <= 0:
                    continue
                w = min(1.0, w) * C[i][j]
                num += w * M[i][j]
                den += w
            row.append(round(1000 * num / den) if den else 500)
        eq.append(tuple(row))

    with open(OUT, "w") as f:
        f.write('"""Generated by tools/build_preflop.py. Do not edit by hand."""\n')
        f.write(f"# order (best first): {' '.join(class_name(k) for k in order[:40])} ...\n")
        f.write(f"XGRID = {XGRID!r}\n")
        f.write("PCT = (" + ", ".join(f"{p:.4f}" for p in pct) + ")\n")
        f.write("EQ = (\n" + "".join(f"    {r!r},\n" for r in eq) + ")\n")
        f.write("EQM = (\n" + "".join(f"    {multi[k]!r},\n" for k in range(169)) + ")\n")
    print(f"wrote {OUT} in {time.time() - t0:.0f}s")
    for name in ("AA", "KK", "AKs", "AKo", "TT", "A5s", "72o", "22", "KTo", "65s"):
        k = next(k for k in range(169) if class_name(k) == name)
        print(f"{name:4s} pct={pct[k]:.3f} vsRand={eqr[k]:.3f} "
              f"vsTop10%={eq[k][XGRID.index(0.10)] / 10:.1f}% vs3rand={multi[k][2] / 10:.1f}%")


if __name__ == "__main__":
    main()
